// Assembles the brag film from the main film's parts, so both draw the board the same way:
//   assets/film-data.js  ← promo/film/assets/film-data.js (game, glyphs)
//   assets/brag.js       ← film.js up to its layout section (curves, palette, Board) + src/scenes.js
//   assets/fonts/*       ← Inter from the film; PingFang subset to this film's copy (uvx fonttools)
// Run: node tools/build.cjs
const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");
const work = path.join(__dirname, "..");
const film = path.join(work, "..", "..", "film");

fs.copyFileSync(path.join(film, "assets", "film-data.js"), path.join(work, "assets", "film-data.js"));

const src = fs.readFileSync(path.join(film, "assets", "film.js"), "utf8");
const cut = src.indexOf("  // ------------------------------------------------------------------ layout");
if (cut < 0) throw new Error("film.js layout marker not found");
const scenes = fs.readFileSync(path.join(work, "src", "scenes.js"), "utf8");
fs.writeFileSync(path.join(work, "assets", "brag.js"),
  "// GENERATED by tools/build.cjs from promo/film/assets/film.js + src/scenes.js. Edit those.\n" + src.slice(0, cut) + scenes + "\n})();\n");

const fonts = path.join(film, "assets", "fonts");
for (const f of ["InterDisplay-SemiBold.otf", "InterDisplay-Medium.otf", "Inter-Regular.otf"]) fs.copyFileSync(path.join(fonts, f), path.join(work, "assets", "fonts", f));
const text = new Set("赠岛 · Gift Islands→0123456789 下棋，还要送对方一子？每一手枚给自己。位置反而少座的获胜开始对局giftislands.top三档AI随时弈");
for (const w of ["Regular", "Semibold"]) {
  execFileSync("uvx", ["--from", "fonttools", "pyftsubset", path.join(fonts, `PingFangSC-${w}.otf`), `--text=${[...text].join("")}`,
    `--output-file=${path.join(work, "assets", "fonts", `PingFangSC-${w}.subset.otf`)}`, "--layout-features=*"], { stdio: "ignore" });
}
console.log("built assets/brag.js, film-data.js, fonts");
