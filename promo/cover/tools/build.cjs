// Builds one HyperFrames project per cover format and language from the film's parts, so the
// cover draws the board exactly as the film does:
//   <lang>-<fmt>/assets/cover.js  ← film.js up to its layout section (curves, palette, Board) + src/cover.js
//   <lang>-<fmt>/assets/*.css      ← film.css + src/cover.css
//   <lang>-<fmt>/assets/fonts/*    ← Inter from the film; PingFang subset to the cover's copy (uvx fonttools)
// Run: node tools/build.cjs   then   hyperframes snapshot <lang>-<fmt> --at 0.5,1.5,2.5
const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");
const cover = path.join(__dirname, "..");
const film = path.join(cover, "..", "film");

const COPY = {
  zh: { head: "每一手，/都送对方一子。", headOne: "每一手，都送对方一子。", sub: "送对位置，对方反而少一座岛。", brand: "赠岛 · Gift Islands" },
  en: { head: "Every move,/a gift.", headOne: "Every move, a gift.", sub: "Give it in the right place, and they lose an island.", brand: "Gift Islands" },
};
const FORMATS = { "16x9": [1920, 1080], "3x4": [1080, 1440], "9x16": [1080, 1920] };

const src = fs.readFileSync(path.join(film, "assets", "film.js"), "utf8");
const cut = src.indexOf("  // ------------------------------------------------------------------ layout");
if (cut < 0) throw new Error("film.js layout marker not found");
const js = "// GENERATED by tools/build.cjs from promo/film/assets/film.js + src/cover.js. Edit those.\n" +
  src.slice(0, cut) + fs.readFileSync(path.join(cover, "src", "cover.js"), "utf8") + "\n})();\n";

// PingFang subset once, shared by every project.
const fonts = path.join(film, "assets", "fonts");
const shared = path.join(cover, ".fonts");
fs.mkdirSync(shared, { recursive: true });
const chars = new Set(Object.values(COPY.zh).join("") + "0123456789");
for (const w of ["Regular", "Semibold"]) {
  execFileSync("uvx", ["--from", "fonttools", "pyftsubset", path.join(fonts, `PingFangSC-${w}.otf`), `--text=${[...chars].join("")}`,
    `--output-file=${path.join(shared, `PingFangSC-${w}.subset.otf`)}`, "--layout-features=*"], { stdio: "ignore" });
}

const html = (lang, fmt, [w, h]) => `<!doctype html>
<html lang="${lang === "zh" ? "zh-CN" : "en"}"
  data-composition-variables='[{"id":"lang","type":"enum","label":"Language","default":"${lang}","options":[{"value":"zh","label":"中文"},{"value":"en","label":"English"}]},{"id":"theme","type":"enum","label":"Theme","default":"light","options":[{"value":"light","label":"Light"}]}]'>
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${w}, height=${h}" />
    <title>Gift Islands · cover ${fmt}</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <link rel="stylesheet" href="assets/film.css" />
    <link rel="stylesheet" href="assets/cover.css" />
  </head>
  <body style="margin:0;width:${w}px;height:${h}px;overflow:hidden">
    <div id="root" data-composition-id="main" data-start="0" data-duration="3" data-width="${w}" data-height="${h}" data-format="${fmt}">
      <div id="ground"></div>
      <section id="dir-a" class="dir clip" data-start="0" data-duration="1" data-track-index="0">
        <div id="a-board" class="board"></div>
        <p id="a-head" class="t head"></p>
        <p id="a-sub" class="t sub"></p>
        <div id="a-mark" class="board"></div>
      </section>
      <section id="dir-b" class="dir clip" data-start="1" data-duration="1" data-track-index="0">
        <div id="b-board" class="board"></div>
        <p id="b-head" class="t head"></p>
        <p id="b-sub" class="t sub"></p>
      </section>
      <section id="dir-c" class="dir clip" data-start="2" data-duration="1" data-track-index="0">
        <div id="c-board" class="board"></div>
        <p id="c-eyebrow" class="t brand"></p>
        <p id="c-head" class="t head"></p>
        <p id="c-sub" class="t sub"></p>
      </section>
    </div>
    <script>window.COVER_COPY = ${JSON.stringify(COPY)};</script>
    <script src="assets/film-data.js"></script>
    <script src="assets/cover.js"></script>
  </body>
</html>
`;

const langs = process.argv.slice(2).length ? process.argv.slice(2) : ["zh", "en"];
for (const lang of langs) for (const [fmt, size] of Object.entries(FORMATS)) {
  const dir = path.join(cover, `${lang}-${fmt}`);
  const assets = path.join(dir, "assets");
  fs.mkdirSync(path.join(assets, "fonts"), { recursive: true });
  fs.writeFileSync(path.join(dir, "index.html"), html(lang, fmt, size));
  fs.writeFileSync(path.join(assets, "cover.js"), js);
  fs.copyFileSync(path.join(film, "assets", "film.css"), path.join(assets, "film.css"));
  fs.copyFileSync(path.join(cover, "src", "cover.css"), path.join(assets, "cover.css"));
  fs.copyFileSync(path.join(film, "assets", "film-data.js"), path.join(assets, "film-data.js"));
  for (const f of ["InterDisplay-SemiBold.otf", "InterDisplay-Medium.otf", "Inter-Regular.otf"]) fs.copyFileSync(path.join(fonts, f), path.join(assets, "fonts", f));
  for (const w of ["Regular", "Semibold"]) fs.copyFileSync(path.join(shared, `PingFangSC-${w}.subset.otf`), path.join(assets, "fonts", `PingFangSC-${w}.subset.otf`));
  console.log(`built ${lang}-${fmt}`);
}
